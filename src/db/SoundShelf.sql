CREATE OR REPLACE PROCEDURE SP_INSERT_CANCION(
    p_idUsuario IN Usuario.idUsuario%TYPE,
    p_titulo IN Cancion.titulo%TYPE,
    p_genero IN Cancion.genero%TYPE,
    p_calificacion IN Cancion.calificacion%TYPE,
    p_comentario IN Cancion.comentario%TYPE,
    p_artista IN Cancion.artista%TYPE,
    p_album IN Cancion.album%TYPE
)
IS
    v_idCancion Cancion.idCancion%TYPE;
BEGIN
    -- Insertar canción
    INSERT INTO Cancion (titulo, genero, calificacion, comentario, artista, album)
    VALUES (p_titulo, p_genero, p_calificacion, p_comentario, p_artista, p_album)
    RETURNING idCancion INTO v_idCancion;

    -- Relacionar con usuario
    INSERT INTO CancionXUsuario (idUsuario, idCancion)
    VALUES (p_idUsuario, v_idCancion);

    COMMIT;
END;
