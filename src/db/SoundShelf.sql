CREATE OR REPLACE PROCEDURE SP_UPDATE_USUARIO(
    p_idUsuario IN Usuario.idUsuario%TYPE,
    p_nombre IN Usuario.nombreUsuario%TYPE,
    p_correo IN Usuario.correo%TYPE
