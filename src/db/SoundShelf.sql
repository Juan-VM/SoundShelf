/* ----------- ESTADISTICAS DEL DASHBOARD (PROCEDIMIENTO 3)----------- */
/*
    Este procedimiento se usa para que cuando el usuario se logea le muestre
    en la pantalla del dashboard varias estadisticas. En el codigo recibe el
    id del usuario establecido en la session y lo usa para hacer out de los 3
    valores que se muestran en las estadistcas.
*/
CREATE OR REPLACE PROCEDURE sp_dashboard_stats(
    p_idUsuario IN Usuario.idUsuario%TYPE,
    p_totalCanciones OUT NUMBER,
    p_totalArtistas OUT NUMBER,
    p_totalListas OUT NUMBER
)
IS
BEGIN
    /* Funcion de cada SELECT:
        - 1 Total canciones del usuario
        - 2 Total artistas distintos
        - 3 Total listas
    */
    SELECT COUNT(*)
    INTO p_totalCanciones
    FROM CancionXUsuario
    WHERE idUsuario = p_idUsuario;


    SELECT COUNT(DISTINCT c.artista)
    INTO p_totalArtistas
    FROM Cancion c
        JOIN CancionXUsuario cu ON c.idCancion = cu.idCancion
    WHERE cu.idUsuario = p_idUsuario;


    SELECT COUNT(*)
    INTO p_totalListas
    FROM Lista
    WHERE idUsuario = p_idUsuario;

EXCEPTION
    WHEN OTHERS THEN
    -- Por aquello de que truene devuelve 0 en todo 
        p_totalCanciones := 0;
        p_totalArtistas := 0;
        p_totalListas := 0;
END;



/* ----------- OBTENER CANCIONES DEL USUARIO (FUNCION 1) ----------- */
/*
    Esta funcion se encarga de retornar  todas las canciones del usuario
    en un cursor para mostarlas en la pnatalla de dashboard.
    Recibe el id que esta seteado en la session, para obtener las canciones
    del usuario. Cuando se retorna el cursor, en el codigo se recorre para 
    generar dinamicamente los elemtos visuales de cada cancion osea obtener
    su informacion.
*/
CREATE OR REPLACE FUNCTION fn_obtener_canciones_usuario(
    p_idUsuario IN Usuario.idUsuario%TYPE
) RETURN SYS_REFCURSOR
IS
    v_cursor SYS_REFCURSOR;
BEGIN
    OPEN v_cursor FOR
        SELECT 
            c.idCancion,
            c.titulo,
            c.artista,
            c.album,
            c.genero,
            c.calificacion
        FROM Cancion c
        JOIN CancionXUsuario cu ON c.idCancion = cu.idCancion
        WHERE cu.idUsuario = p_idUsuario;

    RETURN v_cursor;
END;


