CREATE OR REPLACE PROCEDURE SP_DELETE_CANCION(
    p_idCancion IN Cancion.idCancion%TYPE
)
IS
BEGIN
    -- Eliminar relaciones con listas
    DELETE FROM CancionXLista
    WHERE idCancion = p_idCancion;

    -- Eliminar relación con usuario
    DELETE FROM CancionXUsuario
    WHERE idCancion = p_idCancion;

    -- Eliminar canción
    DELETE FROM Cancion
    WHERE idCancion = p_idCancion;

    COMMIT;
END;
